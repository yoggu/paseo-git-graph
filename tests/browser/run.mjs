const server = createServer(async (request, response) => {
  try {
    if (request.url === '/fixture-change') {
      writeFileSync(join(root, 'file.txt'), 'fresh version\n')
      response.end('updated')
    } else if (request.url === '/fixture-ahead') {
      const tree = git('rev-parse', 'HEAD^{tree}')
      const first = git('commit-tree', tree, '-p', git('rev-parse', 'HEAD^'), '-m', 'Ahead branch one')
      const second = git('commit-tree', tree, '-p', first, '-m', 'Ahead branch two')
      git('update-ref', 'refs/heads/ahead', second)
      response.end('created')
    } else if (request.url === '/fixture-update-remote') {
      const parent = git('--git-dir', remote, 'rev-parse', 'refs/heads/main')
      const tree = git('--git-dir', remote, 'rev-parse', 'refs/heads/main^{tree}')
      const next = git('--git-dir', remote, '-c', 'user.name=Browser remote', '-c', 'user.email=browser@example.invalid', 'commit-tree', tree, '-p', parent, '-m', 'Remote browser update')
      git('--git-dir', remote, 'update-ref', 'refs/heads/main', next)
      response.end('remote updated')
    } else if (request.url === '/fixture-checkout-ahead') {
      git('checkout', '-q', 'ahead')
      response.end('checked out')
    } else if (request.url === '/fixture-detach') {
      git('checkout', '-q', '--detach', 'HEAD')
      response.end('detached')
    } else if (request.url === '/fixture-clean') {
      git('reset', '--hard', 'HEAD')
      git('clean', '-fd')
      response.end('cleaned')
    } else if (request.url === '/unavailable') {
      available = false; response.end('unavailable')
    } else if (request.url === '/available') {
      available = true; response.end('available')
    } else if (request.url === '/rpc') {
      let body = ''
      for await (const chunk of request) body += chunk
      response.setHeader('Content-Type', 'application/json')
      response.end(JSON.stringify(await requestGit(JSON.parse(body), { paseo })))
    } else if (request.url === '/bundle.js') {
      response.setHeader('Content-Type', 'application/javascript')
      response.end(readFileSync(join(temporary, 'bundle.js')))
    } else {
      response.setHeader('Content-Type', 'text/html')
      response.end('<html><body style="margin:0"><div id="root" style="height:100vh;display:flex;flex-direction:column"></div><script src="/bundle.js"></script></body></html>')
    }
  } catch (error) { response.statusCode = 500; response.end(String(error)) }
})
